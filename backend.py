class TravelState(TypedDict):
    """
    Defines the structure of the shared state used by LangGraph.

    Each field stores information that different workflow nodes
    can read or update while planning a trip.

    guardrail_allowed:	Indicates whether the request passed validation.
    guardrail_reason:	Explains why a request was allowed or rejected.
    selected_agents:	Stores the specialist agents selected by the Supervisor.
    trip_constraints:	Holds structured data such as origin, destination, dates, and budget.
    supervisor_reasoning:	Stores a concise routing explanation, not private chain-of-thought.
    budget_results:	Stores the budget breakdown and estimated travel costs.
    approval_requests:	Stores one or more approval requests with relevant details.
    approved:	None means pending; True means approved; False means rejected.
    human_feedback:	Records the user's decision or requested changes.
    final_response:	Holds the response returned to the frontend.
    """

    # Conversation and user request
    messages: Annotated[list[AnyMessage], operator.add]
    user_query: str

    # Guardrail state
    guardrail_allowed: bool
    guardrail_reason: str

    # Supervisor state
    selected_agents: list[str]
    trip_constraints: dict[str, Any]
    supervisor_reasoning: str

    # Original specialist results
    flight_results: str
    hotel_results: str
    weather_results: str
    itinerary: str
    budget_results: str

    # Human-in-the-loop (HITL)
    approval_requests: str
    approved: bool
    human_feedback: str

    # Final response and execution metrics
    final_response: str
    llm_calls: int

